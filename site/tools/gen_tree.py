#!/usr/bin/env python3
"""Write site/data/tree.js: the skill's file tree with a one-line description and the first lines of each file.

Run from anywhere: python3 site/tools/gen_tree.py  (paths are resolved from this file's location)."""
import json, os

ROOT = os.path.normpath(os.path.join(os.path.dirname(__file__), '..', '..'))
SKILL = os.path.join(ROOT, 'skills', 'playme')
OUT = os.path.join(ROOT, 'site', 'data', 'tree.js')
HEAD_LINES = 18

# Order and descriptions shown on the homepage. Files missing on disk are skipped.
ENTRIES = [
    ('SKILL.md', 'The workflow, the 18 rules, the reader budgets', '工作流程、18 条规则、读者负担预算'),
    ('references/', 'Read when needed', '按需阅读'),
    ('references/patterns.md', 'Nine lab patterns with kit sketches', '九种实验模式与组件库示例'),
    ('references/review-loop.md', 'Review protocol and the OpenGCUA ledger', '评审流程与 OpenGCUA 评审记录'),
    ('references/fidelity.md', 'Staying true to the paper', '与论文保持一致'),
    ('references/words.md', 'Precise, plain words; glossary method', '准确平实的用词；术语表方法'),
    ('references/visual.md', 'Visual identity: dark bench, light devices', '视觉：深色台面、真实设备'),
    ('references/kit.md', 'Full API of the lab kit', '组件库的完整 API'),
    ('references/ship-and-promote.md', 'One offline file, embedding, promo media', '离线单文件、嵌入主页、宣传素材'),
    ('kit/', 'The lab kit (plain JS + CSS)', '组件库（纯 JS + CSS）'),
    ('kit/playme.js', 'Part template, player, code pane, folds', '部件模板、播放器、代码面板、折叠区'),
    ('kit/playme-desk.js', 'Mac, browser, phone and terminal frames', 'Mac、浏览器、手机与终端外框'),
    ('kit/playme-3d.js', 'Exploded 3D view on three.js', '基于 three.js 的 3D 拆解视图'),
    ('scripts/', 'Build and check', '构建与检查'),
    ('scripts/bundle.py', 'One self-contained offline file', '打包成一个离线文件'),
    ('scripts/lint.mjs', 'Reader budgets, overflow, console errors', '读者负担预算、溢出、报错'),
    ('scripts/fidelity.py', 'Quotes, references, facts vs the paper', '引文、引用、数字与论文核对'),
    ('scripts/capture.mjs', 'Frame-exact GIF and MP4 from any player', '从任意播放器逐帧导出 GIF/MP4'),
    ('templates/', 'Starter, plan, ledger, facts, words', '起步模板、计划、评审记录、事实与术语'),
    ('templates/starter/index.html', 'A working page with one part', '一个部件的可运行页面'),
    ('templates/starter/parts/01-retry.js', 'One complete part to copy', '可直接复制的完整部件'),
    ('templates/plan.md', 'The plan you show the authors first', '先给作者看的计划'),
    ('templates/facts.json', 'Every number with its place in the paper', '每个数字及其论文出处'),
]

def head(path):
    with open(path, encoding='utf-8', errors='replace') as f:
        lines = []
        for i, line in enumerate(f):
            if i >= HEAD_LINES:
                lines.append('…')
                break
            lines.append(line.rstrip('\n'))
    return '\n'.join(lines)

items = []
for rel, en, zh in ENTRIES:
    p = os.path.join(SKILL, rel.rstrip('/'))
    if not os.path.exists(p):
        continue
    d = rel.endswith('/')
    item = {'path': 'playme/' + rel.rstrip('/'), 'dir': d, 'desc': {'en': en, 'zh': zh}}
    if not d:
        item['head'] = head(p)
    items.append(item)

with open(OUT, 'w', encoding='utf-8') as f:
    f.write('/* Generated by site/tools/gen_tree.py — do not edit. */\nwindow.PMSiteTree = ')
    json.dump(items, f, ensure_ascii=False, indent=1)
    f.write(';\n')
print('wrote', OUT, len(items), 'entries')
